# frozen_string_literal: true

# Dumps the Unicode bidi class of every code point as TwitterCldr knows it
# (`TwitterCldr::Shared::CodePoint.get(cp).bidi_class`, used by `TextUtils.maybe_rtl_reverse`)
# as ranges, so the Rust port of its Bidi algorithm classifies text the same way.
#
# Each line is `first last class` in hexadecimal code points. Code points that
# `CodePoint.get` returns nil for (unassigned, or outside any block) are left out.
# Lines `rtl first last` list the code points `TextUtils::RTL_REGEXP` matches.

blocks = TwitterCldr.get_resource(:unicode_data, :blocks)
classes = {}

blocks.each do |name, range|
  data = TwitterCldr.get_resource(:unicode_data, :blocks, name)
  next unless data

  # `CodePoint.get_range_start`: code points missing from a block that starts with a
  # `<…, First>` range take the class of its first code point.
  start = data[data.keys.min]
  range_class = start[4] if start && start[1].to_s.match?(/<.*, First>/)

  range.each do |code_point|
    # `CodePoint.get_block` takes the first block containing the code point.
    next if classes.key?(code_point)

    fields = data[code_point]
    bidi_class = fields ? fields[4] : range_class
    classes[code_point] = bidi_class if bidi_class
  end
end

lines = []
classes.keys.sort.each do |code_point|
  bidi_class = classes[code_point]
  last = lines.last
  if last && last[1] == code_point - 1 && last[2] == bidi_class
    last[1] = code_point
  else
    lines << [code_point, code_point, bidi_class]
  end
end

rtl = []
(0..0x10FFFF).each do |code_point|
  next if code_point.between?(0xD800, 0xDFFF) || ![code_point].pack('U').match?(TextUtils::RTL_REGEXP)

  if rtl.last && rtl.last[1] == code_point - 1
    rtl.last[1] = code_point
  else
    rtl << [code_point, code_point]
  end
end

puts '# Generated by rust/scripts/dump-bidi-classes.sh from twitter_cldr; do not edit.'
lines.each { |first, last, bidi_class| puts format('%<first>X %<last>X %<class>s', first:, last:, class: bidi_class) }
rtl.each { |first, last| puts format('rtl %<first>X %<last>X', first:, last:) }
