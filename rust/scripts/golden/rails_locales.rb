# frozen_string_literal: true

# Dumps the translations that gems add to Rails (Devise messages, rails-i18n error
# messages, dates and numbers) so the Rust server can use them without the gems.
# Keys defined in config/locales are left out; the Rust server loads those directly.

app_files = Dir[Rails.root.join('config/locales/*.yml')]
gem_backend = I18n::Backend::Simple.new
(I18n.load_path.map(&:to_s) - app_files).each { |f| gem_backend.load_translations(f) }

app_backend = I18n::Backend::Simple.new
app_files.each { |f| app_backend.load_translations(f) }

TOP_KEYS = %i[devise errors activerecord activemodel date time datetime number helpers support].freeze

def strip_app_keys(tree, app_tree)
  tree.each_with_object({}) do |(key, value), out|
    app_value = app_tree.is_a?(Hash) ? app_tree[key] : nil
    if value.is_a?(Hash)
      nested = strip_app_keys(value, app_value)
      out[key.to_s] = nested if nested.present?
    elsif app_value.nil? && !value.is_a?(Proc)
      out[key.to_s] = value
    end
  end
end

result = I18n.available_locales.each_with_object({}) do |locale, out|
  tree = gem_backend.send(:translations)[locale].to_h.slice(*TOP_KEYS)
  app_tree = app_backend.send(:translations)[locale].to_h
  stripped = strip_app_keys(tree, app_tree)
  out[locale.to_s] = stripped if stripped.present?
end

puts "# Generated by rust/scripts/dump-rails-locales.sh from the Rails gems; do not edit."
puts result.to_yaml(line_width: -1).sub(/\A---\n/, '')
