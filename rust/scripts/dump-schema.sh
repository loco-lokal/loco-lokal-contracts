#!/usr/bin/env bash
# Regenerates rust/schema/baseline.sql from the Rails-migrated dev database in
# compose.rust-dev.yml. Run after Rails migrations change; CI and `#[sqlx::test]`
# load this file to get the same schema without running Rails.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/rust/schema/baseline.sql"
PG=(docker compose -f "$ROOT/compose.rust-dev.yml" exec -T postgres)

VERSION="$("${PG[@]}" psql -U docuseal -d docuseal -Atc 'SELECT MAX(version) FROM schema_migrations')"

{
  echo "-- Generated by rust/scripts/dump-schema.sh from the Rails-migrated dev database."
  echo "-- Rails schema version: $VERSION"
  "${PG[@]}" pg_dump -U docuseal -d docuseal --schema-only --no-owner --no-privileges \
    --exclude-table='rust_*' --exclude-table=_sqlx_migrations --exclude-schema=_sqlx_test
  "${PG[@]}" pg_dump -U docuseal -d docuseal --data-only --inserts --no-owner \
    --table=schema_migrations --table=ar_internal_metadata
} | grep -vE '^\\(un)?restrict ' > "$OUT"

echo "Wrote $OUT (schema version $VERSION)"
